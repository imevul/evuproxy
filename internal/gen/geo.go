const ipDenyCountryURL = "https://www.ipdeny.com/ipblocks/data/countries/%s.zone"

// validGeoLine reports whether a zone line is a well-formed IPv4/IPv6 address or
// CIDR. Zone files come from an external source (ipdeny.com) and are interpolated
// verbatim into nftables `add element` statements loaded as root, so every line
// must be validated before use to prevent a compromised/MITM response from
// injecting arbitrary ruleset text.
func validGeoLine(line string) bool {
	if strings.Contains(line, "/") {
		_, _, err := net.ParseCIDR(line)
		return err == nil
	}
	return net.ParseIP(line) != nil
}

// ipDenyRequestPause is the delay between successive zone downloads (IPDeny suggests 0.5–1s; see https://www.ipdeny.com/usagelimits.php).
const ipDenyRequestPause = 750 * time.Millisecond

// GeoLoaderNFT writes a file that flushes and repopulates geo sets in both inet
// and ip tables: the global set plus any per-route custom geo sets (declared
// empty by the table renderer and populated here at apply time).
func GeoLoaderNFT(c *config.Config, zoneDir string) (string, error) {
	if !c.Geo.Enabled {
		return "", fmt.Errorf("geo is disabled in config")
	}
	set := c.Geo.EffectiveSetName()
	var elems []string
	for _, cc := range c.Geo.Countries {
		cc = strings.ToLower(strings.TrimSpace(cc))
		path := filepath.Join(zoneDir, cc+".zone")
		b, err := os.ReadFile(path)
		if err != nil {
			return "", fmt.Errorf("read zone %s: %w", path, err)
		}
		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			if !validGeoLine(line) {
				return "", fmt.Errorf("zone %s: invalid IP/CIDR line %q", path, line)
			}
			elems = append(elems, line)
		}
	}
	if len(elems) == 0 {
		return "", fmt.Errorf("no IP ranges loaded for geo (empty zone files?)")
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by evuproxy update-geo\n")
	writeGeoLoaderSet(&b, set, elems)
	for i, r := range c.Forwarding.Routes {
		if r.Disabled || !strings.EqualFold(strings.TrimSpace(r.GeoMode), config.RouteGeoCustom) {
			continue
		}
		routeElems, err := ZoneCIDRsForCountries(zoneDir, r.GeoCountries)
		if err != nil {
			return "", fmt.Errorf("forwarding.routes[%d] geo_countries: %w", i, err)
		}
		if len(routeElems) == 0 {
			return "", fmt.Errorf("forwarding.routes[%d]: no CIDRs loaded for custom geo", i)
		}
		writeGeoLoaderSet(&b, routeGeoSetName(i), routeElems)
	}
	return b.String(), nil
}

// writeGeoLoaderSet emits flush + repopulate statements for one set in both tables.
func writeGeoLoaderSet(b *strings.Builder, set string, elems []string) {
	payload := strings.Join(elems, ", ")
	fmt.Fprintf(b, "flush set inet evuproxy %s\n", set)
	fmt.Fprintf(b, "add element inet evuproxy %s { %s }\n", set, payload)
	fmt.Fprintf(b, "flush set ip evuproxy %s\n", set)
	fmt.Fprintf(b, "add element ip evuproxy %s { %s }\n", set, payload)
}

// DownloadZones fetches country zone files into zoneDir. The passed context
// bounds the whole operation (each request also has its own transport timeout).
func DownloadZones(ctx context.Context, c *config.Config) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := os.MkdirAll(c.Geo.ZoneDir, 0o755); err != nil {
		return err
	}
	countries := GeoDownloadCountries(c)
	client := &http.Client{Timeout: 2 * time.Minute}
	for i, cc := range countries {
		url := fmt.Sprintf(ipDenyCountryURL, cc)
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
		if err != nil {
			return err
		}
		resp, err := client.Do(req)
		if err != nil {
			return fmt.Errorf("download %s: %w", url, err)
		}
		body, err := io.ReadAll(resp.Body)
		resp.Body.Close()
		if err != nil {
			return err
		}
		if resp.StatusCode != http.StatusOK {
			return fmt.Errorf("download %s: HTTP %s", url, resp.Status)
		}
		out := filepath.Join(c.Geo.ZoneDir, cc+".zone")
		if err := atomicio.WriteFile(out, body, 0o644); err != nil {
			return err
		}
		if i < len(countries)-1 {
			time.Sleep(ipDenyRequestPause)
		}
	}
	return nil
}

// GeoDownloadCountries returns the deduplicated, normalized union of the global
// geo countries and every non-disabled route's custom geo_countries, so custom
// route zones are fetched alongside the global ones.
func GeoDownloadCountries(c *config.Config) []string {
	seen := map[string]struct{}{}
	var out []string
	add := func(cc string) {
		cc = strings.ToLower(strings.TrimSpace(cc))
		if cc == "" {
			return
		}
		if _, ok := seen[cc]; ok {
			return
		}
		seen[cc] = struct{}{}
		out = append(out, cc)
	}
	for _, cc := range c.Geo.Countries {
		add(cc)
	}
	for _, r := range c.Forwarding.Routes {
		if r.Disabled || !strings.EqualFold(strings.TrimSpace(r.GeoMode), config.RouteGeoCustom) {
			continue
		}
		for _, cc := range r.GeoCountries {
			add(cc)
		}
	}
	return out
}
