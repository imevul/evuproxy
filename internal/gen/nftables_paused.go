package gen

import (
	"fmt"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/imevul/evuproxy/internal/config"
)

// pausedRouteComment marks the rule that replaces a paused route's DNAT. The marker is how the
// live chain says which routes are paused, so nothing else has to remember it: a full reload
// removes the markers along with the rest of the old ruleset.
const pausedRouteComment = "evuproxy-paused:"

var pausedRouteCommentRE = regexp.MustCompile(`comment "` + pausedRouteComment + `(\d+)"`)

// NATPreroutingUpdate renders an nft file that rewrites only the live prerouting chain, with no
// DNAT for the routes at the paused indexes of c.Forwarding.Routes. It has to be loaded over a
// ruleset rendered from the same c: the rules use that ruleset's sets, which it doesn't touch,
// so geo sets stay populated and the filter table keeps its CrowdSec bans and rate-limit state.
func NATPreroutingUpdate(c *config.Config, paused []int) (string, error) {
	routes, err := routePolicies(c)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by evuproxy for paused routes — do not edit.\n\n")
	fmt.Fprintf(&b, `flush chain ip evuproxy prerouting
table ip evuproxy {
    chain prerouting {
        type nat hook prerouting priority -100;
`)
	writeNATPreroutingRules(&b, routes, paused)
	fmt.Fprintf(&b, `    }
}
`)
	return b.String(), nil
}

// PausedRoutesIn returns the sorted route indexes marked as paused in nft rules, which can be
// a rendered update or the output of `nft list chain`.
func PausedRoutesIn(rules string) []int {
	var out []int
	for _, m := range pausedRouteCommentRE.FindAllStringSubmatch(rules, -1) {
		if i, err := strconv.Atoi(m[1]); err == nil {
			out = append(out, i)
		}
	}
	slices.Sort(out)
	return slices.Compact(out)
}

func writeNATPreroutingRules(b *strings.Builder, routes []routePolicy, paused []int) {
	for _, r := range routes {
		if slices.Contains(paused, r.routeIndex) {
			writePausedRouteDrop(b, r)
			continue
		}
		for _, line := range r.dnat {
			writePolicyDnatLine(b, r, line)
		}
	}
}

// writePausedRouteDrop closes a paused route's public ports. Leaving them out of the chain isn't
// enough: the packet would stay addressed to this host and reach the route's accept in the input
// chain. That would expose anything listening on the port here, and the conntrack entry it leaves
// would keep a UDP client that doesn't stop sending away from the DNAT after the route resumes.
// Routes can't share a public port, so this can't catch another route's traffic.
func writePausedRouteDrop(b *strings.Builder, r routePolicy) {
	fmt.Fprintf(b, "        %s dport %s %sdrop comment \"%s%d\"\n", r.proto, r.portExpr, r.counter, pausedRouteComment, r.routeIndex)
}
